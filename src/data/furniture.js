// Helper functions
export function getFurnitureBySpace(spaceId) {
  return FURNITURE_DATA.filter((item) => item.spaces.includes(spaceId));
}

export function getFurnitureByCategory(spaceId, categoryId) {
  const spaceItems = getFurnitureBySpace(spaceId);
  if (!categoryId || categoryId === 'all') {
    return spaceItems;
  }
  return spaceItems.filter((item) => item.category === categoryId);
}

export function getFurnitureById(furnitureId) {
  return FURNITURE_DATA.find((item) => item.id === furnitureId) || null;
}
